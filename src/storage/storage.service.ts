import { randomUUID } from 'node:crypto';
import { mkdir, unlink, writeFile } from 'node:fs/promises';
import { dirname, join, resolve, sep } from 'node:path';
import { BadRequestException, Injectable, Logger } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import type { Env } from '../config/env.validation.js';
import { detectImageType } from './image-type.js';

/** Max size of one uploaded image. The apps compress photos well below this. */
export const MAX_IMAGE_BYTES = 1024 * 1024;

/**
 * Saves uploads to the local disk. The database stores paths relative to
 * UPLOADS_DIR (e.g. "products/<storeId>/<uuid>.jpg"); responses turn them
 * into full URLs with PUBLIC_UPLOADS_URL.
 */
@Injectable()
export class StorageService {
  private readonly logger = new Logger(StorageService.name);
  private readonly root: string;
  private readonly publicUrl: string;

  constructor(config: ConfigService<Env, true>) {
    this.root = resolve(config.get('UPLOADS_DIR', { infer: true }));
    this.publicUrl = config
      .get('PUBLIC_UPLOADS_URL', { infer: true })
      .replace(/\/+$/, '');
  }

  get rootDir(): string {
    return this.root;
  }

  /** Validates and saves an image. Returns its relative path. */
  async saveImage(folder: string, file: Express.Multer.File): Promise<string> {
    if (file.size > MAX_IMAGE_BYTES) {
      throw new BadRequestException('Image must be 1 MB or smaller');
    }
    const extension = detectImageType(file.buffer);
    if (!extension) {
      throw new BadRequestException('Image must be a JPEG, PNG or WebP file');
    }
    const relativePath = `${folder}/${randomUUID()}.${extension}`;
    const absolutePath = this.absolutePath(relativePath);
    await mkdir(dirname(absolutePath), { recursive: true });
    await writeFile(absolutePath, file.buffer);
    return relativePath;
  }

  /** Deletes a previously saved file. Never throws: a leftover file is harmless. */
  async delete(relativePath: string | null | undefined): Promise<void> {
    if (!relativePath || isExternalUrl(relativePath)) return;
    try {
      await unlink(this.absolutePath(relativePath));
    } catch (error) {
      this.logger.warn(`Could not delete ${relativePath}: ${String(error)}`);
    }
  }

  /** Full URL for a stored path. Already-absolute URLs are returned as is. */
  url(relativePath: string | null | undefined): string | null {
    if (!relativePath) return null;
    if (isExternalUrl(relativePath)) return relativePath;
    return `${this.publicUrl}/${relativePath}`;
  }

  private absolutePath(relativePath: string): string {
    const absolute = resolve(join(this.root, relativePath));
    // Paths are generated by us, but never touch anything outside the root.
    if (!absolute.startsWith(this.root + sep)) {
      throw new Error(`Path escapes the uploads folder: ${relativePath}`);
    }
    return absolute;
  }
}

function isExternalUrl(path: string): boolean {
  return /^https?:\/\//.test(path);
}
